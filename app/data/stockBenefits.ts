/** 同一銘柄コードの重複条は1件に統合したシード（検索・一覧・findSeedBenefit で共通） */
export const seedStockBenefits: StockBenefit[] = dedupeSeedStockBenefits(seedStockBenefitsRaw);

let seedBenefitSearchHaystackCache: Map<string, string> | null = null;

/** 銘柄コード単位に、優待シードの本文・注記を検索用 haystack に連結（複数条は併記）。 */
export const getSeedBenefitSearchHaystack = (stockCode: string): string => {
  if (!seedBenefitSearchHaystackCache) {
    const acc = new Map<string, string[]>();
    for (const b of seedStockBenefits) {
      const chunk = [b.content, b.notes, b.longTermNote].filter(Boolean).join(" ");
      if (!chunk) continue;
      const xs = acc.get(b.stockCode) ?? [];
      xs.push(chunk);
      acc.set(b.stockCode, xs);
    }
    seedBenefitSearchHaystackCache = new Map(
      [...acc.entries()].map(([code, xs]) => [code, xs.join(" ")])
    );
  }
  return seedBenefitSearchHaystackCache.get(stockCode) ?? "";
};

export const findSeedBenefit = (stockCode: string): StockBenefit | undefined => {
  return seedStockBenefits.find((b) => b.stockCode === stockCode);
};

/**
 * StockBenefit の確度ラベルを取得する。
 * confidence が未指定の場合、内容が「実施なし」を示すなら "abolished"、
 * それ以外は "stable" を返す（実用上の安全側デフォルト）。
 */
export const getEffectiveConfidence = (benefit: StockBenefit): BenefitConfidence => {
  if (benefit.confidence) return benefit.confidence;
  if (benefit.minShares === 0 && benefit.rightsMonths === "-") return "abolished";
  if (/実施なし|廃止/.test(benefit.content)) return "abolished";
  return "stable";
};

