/**
 * 株主優待の確度ラベル。
 *  - "verified": 公式IRや信頼ソースで直近に検証済み（lastConfirmedAtと併用）
 *  - "stable": 長年継続している制度で大きな変更なし（精度は中程度）
 *  - "uncertain": 情報が古い・廃止/改悪の可能性あり、要確認
 *  - "abolished": 廃止が確認済み
 */
export type BenefitConfidence = "verified" | "stable" | "uncertain" | "abolished";

export type StockBenefit = {
  stockCode: string;
  content: string;
  rightsMonths: string;
  minShares: number;
  longTermNote?: string;
  yieldPercent?: number;
  notes?: string;
  /**
   * 公式IRページ等のURL。ユーザーが自分で最新情報を検証できるようにする。
   */
  irUrl?: string;
  /**
   * 最終確認日（YYYY-MM-DD）。空ならまだ検証ログがない＝信頼度低め。
   */
  lastConfirmedAt?: string;
  /**
   * 情報の確度ラベル。未指定なら "stable" 扱い。
   */
  confidence?: BenefitConfidence;
  /**
   * 企業が IR / 株主総会招集通知等で案内している発送時期（自由記述）。
   * 例: "6月下旬", "11月上旬発送予定", "権利確定後3ヶ月以内"。
   * ユーザー投稿がまだ少ない銘柄でも、これが入っていれば「いつ届く？」の
   * 初期表示に使う。
   * noticeArrival / actualArrival が未入力の銘柄の互換用フィールド。
   */
  expectedArrival?: string;
  /**
   * カタログ・申込書など「案内」が届く時期（自由記述）。
   * 例: "6月下旬"。カタログギフトや選択式優待で「先に案内が来て、後から品物」
   * になるケースを別個に登録できるようにするためのフィールド。
   */
  noticeArrival?: string;
  /**
   * 実際の商品・優待品（カタログ申込後の商品など）が届く時期（自由記述）。
   * 例: "8月〜9月"。
   */
  actualArrival?: string;
  /**
   * 保有株数別の優待内容（株数階段）。
   * 100株→食事券3枚 / 1000株→12枚 のように、株数によって内容が変わる優待を表現する。
   * 配列は minShares 昇順で保存する。
   * tieredBenefits が指定されていれば、UI ではこちらを優先表示する。
   */
  tieredBenefits?: TieredBenefit[];
  /**
   * 編集者が付与するカテゴリバッジ（グルメ・食事券・買物・割引など）。
   * 本文キーワードによる自動判定（detectCategories）とマージして表示される。
   */
  badgeKeys?: BenefitCategoryKey[];
};

/**
 * 株数 × 保有年数の階段（マトリクス）の1段階。
 *  - minShares: その段階に必要な最低保有株数（例: 100, 1000）
 *  - minYears: その段階に必要な最低継続保有年数。未指定 / 0 は「年数条件なし」を意味する。
 *  - content: その株数・保有年数で受け取れる内容（例: "食事券3枚（3,000円相当）"）
 *
 * 例：
 *   { minShares: 100, minYears: 0, content: "食事券3枚" }
 *   { minShares: 100, minYears: 3, content: "食事券6枚（長期）" }
 *   { minShares: 1000, minYears: 0, content: "食事券12枚" }
 *   { minShares: 1000, minYears: 3, content: "食事券18枚（長期）" }
 */
export type TieredBenefit = {
  minShares: number;
  minYears?: number;
  content: string;
};

